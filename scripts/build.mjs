import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
process.chdir(root);
const worklet=await build({entryPoints:['audio/voice-worklet.js'],bundle:true,write:false,format:'iife',target:'es2022',minify:true});
const wasm=await readFile('audio/hermes_tract.wasm');
await writeFile('src/embedded.ts',`// Generated by scripts/build.mjs from the shipped engine and processor.\nexport const wasmBytes=Uint8Array.from(atob(${JSON.stringify(wasm.toString('base64'))}),c=>c.charCodeAt(0));\nexport const workletSource=${JSON.stringify(worklet.outputFiles[0].text)};\n`);
await mkdir('desktop',{recursive:true});
await build({entryPoints:['src/desktop.tsx'],outfile:'desktop/plugin.js',bundle:true,format:'esm',target:'es2022',external:['@hermes/plugin-sdk','react','react/jsx-runtime'],minify:false,legalComments:'eof'});
console.log(`Built desktop/plugin.js with ${wasm.length} bytes of embedded WASM.`);
