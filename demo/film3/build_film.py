"""Lay out the film from film.json: segment times, index.html (scene hosts) and compositions/app.html
(the whole Hermes window with its takes and captions). Run from demo/film3; then ../build_audio3.py.
Writes the resolved timeline to film.resolved.json for the soundtrack builder."""
import json

F = json.load(open('film.json'))
# Resolve app-local times: each segment follows the previous one; a fast-forward lasts (end - media) / rate.
a = 0.0
for s in F['segments']:
    s['a'] = round(a, 3)
    s['dur'] = round((s['end'] - s['media']) / s.get('rate', 1), 3)
    a += s['dur']
app_dur = round(a, 3)
app0 = F['app']['film']
dive0 = round(app_dur - F['dive'], 3)
show_film = round(app0 + app_dur - 0.2, 3)
show_dur = round(F['show']['end'] - F['show']['media'], 3)
end_film = round(show_film + show_dur, 3)
total = round(end_film + F['end']['seconds'], 3)
R = {**F, 'app_dur': app_dur, 'dive_a': [dive0, app_dur], 'show_film': show_film, 'show_dur': show_dur, 'end_film': end_film, 'total': total}
json.dump(R, open('film.resolved.json', 'w'), indent=1)

idx = open('index.html').read()
import re
def host(i, start, dur):
    global idx
    idx = re.sub(rf'(<div id="{i}" data-composition-id="{i}" data-composition-src="compositions/{i}.html" data-start=")[^"]*(" data-duration=")[^"]*(")',
                 rf'\g<1>{start}\g<2>{dur:.2f}\g<3>', idx)
host('app', app0, app_dur)
host('act', show_film, show_dur)
host('end', end_film, F['end']['seconds'])
idx = re.sub(r'(<div id="root" data-composition-id="main" data-start="0" data-duration=")[^"]*(")', rf'\g<1>{total:.2f}\g<2>', idx)
idx = re.sub(r'(<audio id="soundtrack"[^>]*data-duration=")[^"]*(")', rf'\g<1>{total:.2f}\g<2>', idx)
open('index.html', 'w').write(idx)

act = open('compositions/act.html').read()
act = re.sub(r'(id="act-video" class="clip" src="assets/act.mp4" muted playsinline data-start="0" data-duration=")[^"]*(" data-media-start=")[^"]*(")',
             rf'\g<1>{show_dur:.2f}\g<2>{F["show"]["media"]}\g<3>', act)
open('compositions/act.html', 'w').write(act)
end = open('compositions/end.html').read()
end = re.sub(r'(id="end-last" class="clip" src="assets/act.mp4" muted playsinline data-start="0" data-duration="0.6" data-media-start=")[^"]*(")',
             rf'\g<1>{F["show"]["end"] - 0.15:.2f}\g<2>', end)
open('compositions/end.html', 'w').write(end)

vids = []
for s in F['segments']:
    rate = f' data-playback-rate="{s["rate"]}"' if s.get('rate') else ''
    vids.append(f'      <video id="app-{s["id"]}" class="app-take clip" src="assets/{s["take"]}.mp4" muted playsinline data-start="{s["a"]}" data-duration="{s["dur"]}" data-media-start="{s["media"]}"{rate} data-track-index="0"></video>')
caps, capjs = [], []
seg = {s['id']: s for s in F['segments']}
def cap_times(first, last):
    a, b = seg[first], seg[last]
    pad0 = 0.08 if a.get('rate') else 0.3
    pad1 = 0.08 if b.get('rate') else 0.3
    end = b['a'] + b['dur'] - pad1
    if last == F['segments'][-1]['id']:
        end = min(end, dive0 - 0.1)
    return round(a['a'] + pad0, 3), round(end, 3)
F['captions'] = [[f, *cap_times(f, l), t] for f, l, t in F['captions']]
for cid, c0, c1, text in F['captions']:
    words = ' '.join(f'<span class="app-word{" app-key" if w.startswith("*") else ""}">{w.lstrip("*")}</span>' for w in text.split())
    caps.append(f'    <div id="app-cap-{cid}" class="app-cap clip" data-start="{c0}" data-duration="{c1 - c0 + 0.3:.2f}" data-track-index="1">\n      {words}\n    </div>')
    capjs.append(f'["#app-cap-{cid}", {c0}, {c1}]')
mx, my = F['app']['mouth']
app = f'''<template>
  <style>
    #root {{ position: absolute; inset: 0; overflow: hidden; background: var(--color-accent, #2152f4); }}
    /* The whole Hermes window, every pixel of it, as a card on Hermes blue. The takes are 1906×1080 inside
       7 px of white padding, so the card is 1906 wide and the video sits 7 px left. */
    #app-win {{ position: absolute; left: 0; top: 0; width: 1906px; height: 1080px; overflow: hidden; border-radius: 20px; opacity: 0;
      background: #ffffff; transform-origin: 0 0; box-shadow: 0 30px 80px rgba(10, 20, 80, 0.35), 0 4px 14px rgba(10, 20, 80, 0.2); }}
    .app-take {{ position: absolute; left: -7px; top: 0; width: 1920px; height: 1080px; }}
    /* Captions live in the band under the window and never cover it. */
    .app-cap {{ position: absolute; left: 0; top: 963px; width: 1920px; height: 117px; display: flex; align-items: center; justify-content: center;
      font-family: "Inter", sans-serif; font-weight: 700; font-size: 42px; letter-spacing: -0.01em; color: #ffffff; white-space: nowrap; }}
    .app-cap .app-word {{ display: inline-block; margin: 0 0.13em; }}
    .app-cap .app-key {{ color: #ffe27a; }}
  </style>
  <div id="root" data-composition-id="app" data-width="1920" data-height="1080">
    <div id="app-win">
      <!-- Generated by build_film.py from film.json. The agent (a real model, DeepSeek V4.1 Flash on Nous):
           the song request, its reply and card, her singing; the beat request, its reply, the beat.
           Waits for the model are fast-forwarded and captioned so. Then the instrument by hand, the pads, and a jam: the user plays a phrase, the agent writes a sung answer. -->
{chr(10).join(vids)}
    </div>
{chr(10).join(caps)}
  </div>
  <script>
    const tl = gsap.timeline({{ paused: true }});
    const win = "#app-win";
    const REST = {{ scale: 0.86, x: 140, y: 34 }};
    tl.set(win, {{ ...REST, opacity: 0 }}, 0);
    // The window appears under the title's wordmark, which lands exactly on the app's own.
    tl.to(win, {{ opacity: 1, duration: 0.4, ease: "power2.out" }}, 0.1);
    const caps = [{", ".join(capjs)}];
    for (const [id, start, end] of caps) {{
      gsap.utils.toArray(`${{id}} .app-word`).forEach((w, i) =>
        tl.fromTo(w, {{ opacity: 0, y: 14, filter: "blur(6px)" }}, {{ opacity: 1, y: 0, filter: "blur(0px)", duration: 0.22, ease: "power3.out" }}, start + 0.04 + i * 0.06));
      tl.to(`${{id}} .app-word`, {{ opacity: 0, filter: "blur(8px)", duration: 0.18, stagger: 0.02, ease: "power2.in" }}, end);
    }}
    // Dive through her lips into the act: the lips sit at ({mx}, {my}) inside the window.
    const S = 6.5;
    tl.to(win, {{ scale: S, x: 960 - S * {mx}, y: 540 - S * {my}, borderRadius: 0, filter: "blur(14px)", duration: {F['dive']}, ease: "power3.in" }}, {dive0});
    tl.to("#root", {{ opacity: 0, duration: 0.2, ease: "none" }}, {app_dur - 0.2:.3f});
    window.__timelines["app"] = tl;
  </script>
</template>
'''
open('compositions/app.html', 'w').write(app)
print(f'app {app_dur} s (dive at a {dive0}); act {show_film}-{end_film}; total {total} s')
for s in F['segments']:
    print(f"  {s['id']:7} a {s['a']:6.2f}  {s['dur']:5.2f} s  media {s['media']}-{s['end']}" + (f"  ×{s['rate']}" if s.get('rate') else ''))
